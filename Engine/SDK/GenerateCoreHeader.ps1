param(
    [Parameter(Mandatory = $true)]
    [string]$RepositoryRoot,

    [Parameter(Mandatory = $true)]
    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'

$manifestPath = Join-Path $PSScriptRoot 'PublicHeaders.props'
[xml]$manifest = Get-Content -Raw -LiteralPath $manifestPath
$publicHeaders = @($manifest.Project.ItemGroup.CorePublicHeader |
    ForEach-Object { [string]$_.Include })
if ($publicHeaders.Count -eq 0)
{
    throw "The public header manifest is empty: $manifestPath"
}

$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('#pragma once')
[void]$builder.AppendLine()
[void]$builder.AppendLine('// Generated by Engine/SDK/GenerateCoreHeader.ps1.')
[void]$builder.AppendLine('// Do not edit this file directly; edit the feature headers instead.')
[void]$builder.AppendLine()
[void]$builder.AppendLine('#if defined(_MSC_VER) && !defined(PHANTOMCORE_NO_AUTOLINK)')
[void]$builder.AppendLine('#pragma comment(lib, "PhantomCore.lib")')
[void]$builder.AppendLine('#pragma comment(lib, "d3d12.lib")')
[void]$builder.AppendLine('#pragma comment(lib, "d3dcompiler.lib")')
[void]$builder.AppendLine('#pragma comment(lib, "dxgi.lib")')
[void]$builder.AppendLine('#pragma comment(lib, "dxguid.lib")')
[void]$builder.AppendLine('#pragma comment(lib, "windowscodecs.lib")')
[void]$builder.AppendLine('#pragma comment(lib, "dwrite.lib")')
[void]$builder.AppendLine('#if defined(_DEBUG)')
[void]$builder.AppendLine('#pragma comment(lib, "fmodL_vc.lib")')
[void]$builder.AppendLine('#else')
[void]$builder.AppendLine('#pragma comment(lib, "fmod_vc.lib")')
[void]$builder.AppendLine('#endif')
[void]$builder.AppendLine('#endif')
[void]$builder.AppendLine()

foreach ($relativePath in $publicHeaders)
{
    $sourcePath = Join-Path $RepositoryRoot $relativePath
    if (-not (Test-Path -LiteralPath $sourcePath -PathType Leaf))
    {
        throw "Public header was not found: $sourcePath"
    }

    [void]$builder.AppendLine("// ===== BEGIN $relativePath =====")
    foreach ($line in [System.IO.File]::ReadAllLines($sourcePath))
    {
        if ($line -match '^\s*#pragma\s+once\s*$')
        {
            continue
        }
        if ($line -match '^\s*#include\s+"[^"]+"\s*$')
        {
            continue
        }
        [void]$builder.AppendLine($line)
    }
    [void]$builder.AppendLine("// ===== END $relativePath =====")
    [void]$builder.AppendLine()
}

$outputDirectory = Split-Path -Parent $OutputPath
if (-not (Test-Path -LiteralPath $outputDirectory -PathType Container))
{
    [void](New-Item -ItemType Directory -Path $outputDirectory)
}

$encoding = [System.Text.UTF8Encoding]::new($false)
$resolvedOutputPath = [System.IO.Path]::GetFullPath($OutputPath)
$generatedContent = $builder.ToString().TrimEnd() + [Environment]::NewLine
$currentContent = if (Test-Path -LiteralPath $resolvedOutputPath -PathType Leaf)
{
    [System.IO.File]::ReadAllText($resolvedOutputPath)
}

if ($currentContent -cne $generatedContent)
{
    [System.IO.File]::WriteAllText(
        $resolvedOutputPath,
        $generatedContent,
        $encoding)
}
